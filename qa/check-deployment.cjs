const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1600,height:900}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const domain=require('node:fs').readFileSync(require('node:path').join(__dirname,'../deploy/CNAME'),'utf8').trim();
  const url=`https://${domain}/`;
  const response=await page.goto(url,{waitUntil:'load',timeout:60000});
  assert.equal(response.status(),200);
  await page.waitForFunction(()=>typeof window.Presentation?.go==='function');
  assert.equal(await page.locator('.slide').count(),28);
  const presentationAccent=await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--accent').trim());
  assert.ok(await page.locator('img').evaluateAll(images=>images.every(img=>img.complete&&img.naturalWidth>0)));
  await page.evaluate(()=>Presentation.go(20));
  await page.locator('#battle-controls [data-action="finish"]').click();
  const result=await page.evaluate(()=>({SMA:Presentation.battle.sma.bestScore,AO:Presentation.battle.ao.bestScore,iterations:Presentation.battle.sma.iteration}));
  assert.equal(result.iterations,60);
  assert.equal(await page.locator('[data-visualization]').count(),4);
  await page.locator('.slide.active [data-visualization]').click();
  await page.waitForFunction(()=>!!window.AlgorithmLab);
  assert.match(page.url(),/\/visualization\//);
  assert.equal(await page.evaluate(()=>AlgorithmLab.view),'compare');
  assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()),presentationAccent);
  assert.equal(await page.evaluate(()=>AlgorithmLab.scene.debug().mode),'3d');
  await page.locator('#step-button').click();
  assert.equal(await page.evaluate(()=>AlgorithmLab.simulation.cursor),1);
  await page.locator('#focus-button').click();
  assert.equal(await page.evaluate(()=>AlgorithmLab.focusMode),true);
  assert.equal(await page.locator('.sidebar').isVisible(),false);
  assert.equal(await page.locator('#play-button').isVisible(),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>AlgorithmLab.focusMode),false);
  const sceneMode=await page.evaluate(()=>AlgorithmLab.scene.debug().mode);
  await page.locator('[data-view="ao"]').click();
  assert.equal(await page.evaluate(()=>AlgorithmLab.view),'ao');
  await page.locator('#learn-button').click();
  assert.equal(await page.evaluate(()=>AlgorithmLab.lesson.enabled),true);
  const recordedEvaluations=await page.evaluate(()=>AlgorithmLab.simulation.optimizers.AO.evaluations);
  await page.locator('[data-stage="3"]').click();
  assert.match(await page.locator('#lesson-description').innerText(),/pratinjau proposal/);
  assert.equal(await page.locator('#lesson-scene-title').innerText(),'Clip ke [0, 1]');
  assert.equal(await page.locator('#lesson-readout>div').count(),3);
  assert.equal(await page.locator('#lesson-focus-camera').isVisible(),true);
  await page.locator('[data-stage="4"]').click();
  assert.equal(await page.evaluate(()=>AlgorithmLab.scene.scenes.AO.lessonVisual.userData.frame.step),4);
  assert.equal(await page.evaluate(()=>AlgorithmLab.simulation.optimizers.AO.evaluations),recordedEvaluations);
  assert.equal(await page.evaluate(()=>AlgorithmLab.scene.scenes.AO.vmBoundaries.visible),true);
  await page.locator('#close-lesson').click();
  await page.locator('#return-link').click();
  await page.waitForFunction(()=>typeof Presentation?.go==='function');
  assert.equal(await page.evaluate(()=>Presentation.current),20);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:require('node:path').join(__dirname,'surge-live.png')});
  console.log(JSON.stringify({url,status:response.status(),slides:28,simulation:result,sceneMode,visualizationNavigation:'passed',learningMode:'passed',errors}));
  await browser.close();
})();
